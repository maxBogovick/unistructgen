// ✅ THE PRO WAY: Using UniStructGen Core Pipeline
// Modular, Extendable, Robust.

use std::fs;
use anyhow::Result;
use unistructgen_core::{Pipeline, IRTransformer, IRModule, IRType};
use unistructgen_json_parser::{JsonParser, ParserOptions};
use unistructgen_codegen::{RustRenderer, RenderOptions};

// --- 1. Custom Logic (The Power Move) ---
// Imagine your company requires all structs to have specific derives or docs.
// You simply implement the IRTransformer trait.

struct EnterpriseStandard;

impl IRTransformer for EnterpriseStandard {
    fn name(&self) -> &'static str {
        "EnterpriseStandard"
    }

    fn transform(&self, mut module: IRModule) -> Result<IRModule, unistructgen_core::TransformError> {
        // Iterate over all types in the module
        for ty in &mut module.types {
            if let IRType::Struct(s) = ty {
                // 1. Add company-standard derives
                s.add_derive("PartialEq".to_string());
                s.add_derive("Eq".to_string());
                
                // 2. Add documentation to the struct
                s.doc = Some("Auto-generated by Enterprise Pipeline v2.0".to_string());

                // 3. Process fields
                for field in &mut s.fields {
                    // Automatically document fields based on their name
                    if field.name.contains("timeout") {
                         field.doc = Some("Critical timeout value in ms".to_string());
                    }
                }
            }
        }
        Ok(module)
    }
}

fn main() -> Result<()> {
    println!("--- Generating Code (The Pipeline Way) ---");

    // 1. Setup Input
    let json_input = fs::read_to_string("data/legacy.json")?;

    // 2. Build the Pipeline
    let parser = JsonParser::new(ParserOptions {
        struct_name: "SystemConfig".to_string(),
        derive_serde: true,
        ..Default::default()
    });
    
    let generator = RustRenderer::new(RenderOptions::default());

    let mut pipeline = Pipeline::new(parser, generator)
        // Inject our custom logic here!
        .add_transformer(Box::new(EnterpriseStandard));

    // 3. Execute
    let rust_code = pipeline.execute(&json_input).expect("Pipeline failed");

    println!("{}", rust_code);

    Ok(())
}
