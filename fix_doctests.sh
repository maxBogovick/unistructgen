#!/bin/bash
set -e

echo "🔧 Исправляем импорты в doc-тестах..."

# Находим все .rs файлы
find src -name "*.rs" -type f | while read file; do
    # Читаем файл построчно и правим
    # Логика: если строка начинается с "///" (или "//!"), и в ней есть "use crate::", меняем на "use unistructgen::"

    # Используем perl для замены in-place, так как sed сложнее с контекстом
    perl -i -pe 's|///(.*)use crate::|///$1use unistructgen::|g' "$file"
    perl -i -pe 's|//!(.*)use crate::|//!$1use unistructgen::|g' "$file"

    # Также обрабатываем блоки кода ```rust ... ``` внутри документации, если они не на одной строке
    # Но простой замены выше должно хватить для большинства случаев, так как use обычно в начале примера
done

echo "✨ Готово! Попробуйте cargo test снова."
